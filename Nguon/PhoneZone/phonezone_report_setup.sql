-- PhoneZone: database demo matching the report's one-database/five-schema model.
-- Run this file while connected to database: phonezone

CREATE SCHEMA IF NOT EXISTS shop_user;
CREATE SCHEMA IF NOT EXISTS shop_product;
CREATE SCHEMA IF NOT EXISTS shop_order;
CREATE SCHEMA IF NOT EXISTS shop_payment;
CREATE SCHEMA IF NOT EXISTS shop_ai;

CREATE TABLE IF NOT EXISTS shop_user.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status VARCHAR(10) NOT NULL DEFAULT '1',
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  full_name VARCHAR(255), email VARCHAR(255) UNIQUE, phone VARCHAR(25),
  city VARCHAR(255), district VARCHAR(255), address VARCHAR(500), image VARCHAR(500),
  gender VARCHAR(20), role VARCHAR(20) NOT NULL DEFAULT 'USER'
);
CREATE INDEX IF NOT EXISTS idx_users_status ON shop_user.users(status);

CREATE TABLE IF NOT EXISTS shop_user.user_addresses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES shop_user.users(id),
  recipient_name VARCHAR(100) NOT NULL, phone VARCHAR(25) NOT NULL,
  address VARCHAR(500) NOT NULL, address_label VARCHAR(40), is_default BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS shop_product.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT DEFAULT 0, status VARCHAR(10) NOT NULL DEFAULT '1',
  name VARCHAR(255) NOT NULL, price BIGINT CHECK(price >= 0), discount BIGINT DEFAULT 0 CHECK(discount >= 0),
  category VARCHAR(100), image VARCHAR(500), description TEXT, screen VARCHAR(255), battery VARCHAR(100),
  create_date TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_products_status_category_created
  ON shop_product.products(status, category, create_date DESC);

CREATE TABLE IF NOT EXISTS shop_product.product_variants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT DEFAULT 0, product_id BIGINT NOT NULL REFERENCES shop_product.products(id),
  sku VARCHAR(100) NOT NULL, color VARCHAR(60), ram VARCHAR(40), storage VARCHAR(40),
  stock BIGINT NOT NULL DEFAULT 0 CHECK(stock >= 0), price_adjustment BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT uk_variant_product_sku UNIQUE(product_id, sku)
);
CREATE INDEX IF NOT EXISTS idx_variants_product_id ON shop_product.product_variants(product_id);

CREATE TABLE IF NOT EXISTS shop_product.product_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES shop_product.products(id),
  user_id BIGINT REFERENCES shop_user.users(id), username_snapshot VARCHAR(255),
  rating SMALLINT CHECK(rating BETWEEN 1 AND 5), message TEXT NOT NULL,
  create_date TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS shop_order.cart (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES shop_user.users(id),
  variant_id BIGINT NOT NULL REFERENCES shop_product.product_variants(id),
  quantity BIGINT NOT NULL CHECK(quantity > 0), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS shop_order.coupons (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(120), type VARCHAR(12) NOT NULL, value BIGINT NOT NULL CHECK(value >= 0),
  min_order_value BIGINT DEFAULT 0, start_at TIMESTAMPTZ, end_at TIMESTAMPTZ,
  active BOOLEAN NOT NULL DEFAULT TRUE, usage_limit BIGINT, used_count BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS shop_order.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES shop_user.users(id),
  user_name_snapshot VARCHAR(255), delivery_address_snapshot VARCHAR(500),
  order_date TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP, payment_method VARCHAR(20),
  coupon_code_snapshot VARCHAR(40), coupon_discount BIGINT DEFAULT 0,
  quantity_product BIGINT DEFAULT 0, total_price BIGINT DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
);
CREATE INDEX IF NOT EXISTS idx_orders_status_date
  ON shop_order.orders(status, order_date DESC);

CREATE TABLE IF NOT EXISTS shop_order.items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES shop_order.orders(id) ON DELETE CASCADE,
  variant_id BIGINT NOT NULL REFERENCES shop_product.product_variants(id),
  product_name_snapshot VARCHAR(255) NOT NULL, variant_label_snapshot VARCHAR(160),
  unit_price_snapshot BIGINT NOT NULL CHECK(unit_price_snapshot >= 0), discount_snapshot BIGINT DEFAULT 0,
  product_image_snapshot VARCHAR(500), quantity BIGINT NOT NULL CHECK(quantity > 0),
  total BIGINT NOT NULL CHECK(total >= 0)
);
CREATE INDEX IF NOT EXISTS idx_items_order_id ON shop_order.items(order_id);
CREATE INDEX IF NOT EXISTS idx_items_variant_id ON shop_order.items(variant_id);

CREATE TABLE IF NOT EXISTS shop_order.after_sales_cases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, case_code VARCHAR(40) NOT NULL UNIQUE,
  order_id BIGINT NOT NULL REFERENCES shop_order.orders(id), item_id BIGINT REFERENCES shop_order.items(id),
  user_id BIGINT NOT NULL REFERENCES shop_user.users(id), imei VARCHAR(80) NOT NULL,
  request_type VARCHAR(20) NOT NULL, description VARCHAR(2000), status VARCHAR(30) NOT NULL DEFAULT 'CREATED',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS shop_order.after_sales_evidence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id BIGINT NOT NULL REFERENCES shop_order.after_sales_cases(id) ON DELETE CASCADE,
  evidence_url VARCHAR(1000) NOT NULL, evidence_type VARCHAR(30),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS shop_payment.payment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id VARCHAR(100) NOT NULL UNIQUE,
  order_id BIGINT NOT NULL REFERENCES shop_order.orders(id), user_id BIGINT NOT NULL REFERENCES shop_user.users(id),
  amount BIGINT NOT NULL CHECK(amount >= 0), method VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING', transaction_id VARCHAR(100), result_code INTEGER,
  message VARCHAR(500), created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_payment_status_created
  ON shop_payment.payment(status, created_at DESC);

CREATE TABLE IF NOT EXISTS shop_ai.chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session_id VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL, content VARCHAR(4000) NOT NULL, created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS shop_ai.behavior_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT, session_id VARCHAR(80),
  event_type VARCHAR(40) NOT NULL, product_id BIGINT, search_query VARCHAR(300), created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS shop_ai.agent_memories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, session_id VARCHAR(100) NOT NULL UNIQUE,
  product_id BIGINT, expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS shop_ai.recommendation_audits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, subject_key VARCHAR(100) NOT NULL,
  outcome VARCHAR(30), created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS shop_ai.recommendation_audit_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  audit_id BIGINT NOT NULL REFERENCES shop_ai.recommendation_audits(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES shop_product.products(id), rank_position INTEGER,
  UNIQUE(audit_id, product_id)
);

